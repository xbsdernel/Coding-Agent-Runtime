"""Chat-template rendering, tokenization, and prefix-stability verification.

Provides Qwen2.5-Coder ChatML template application, deterministic tokenization,
tool schema rendering, and structured tool-call parsing.
"""

from __future__ import annotations

import json
import re
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from codeagent.schemas import stable_json

# Special tokens in Qwen2.5-Coder ChatML template
IM_START = "<|im_start|>"
IM_END = "<|im_end|>"


class ChatMessage(BaseModel):
    """Single message in a multi-turn chat trajectory."""

    model_config = ConfigDict(extra="forbid")

    role: str = Field(description="Role: 'system', 'user', 'assistant', or 'tool'.")
    content: str = Field(default="", description="Message text payload.")
    name: str | None = Field(default=None, description="Optional name identifier.")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="Optional list of tool calls generated by assistant."
    )
    tool_call_id: str | None = Field(default=None, description="Identifier for tool result.")


class ToolDefinition(BaseModel):
    """Specification for an agent tool conforming to JSON Schema."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(description="Unique name of the tool function.")
    description: str = Field(description="Purpose and semantics of the tool.")
    parameters: dict[str, Any] = Field(
        default_factory=dict, description="JSON Schema for tool arguments."
    )


def apply_chat_template(
    messages: list[ChatMessage | dict[str, Any]],
    tools: list[ToolDefinition | dict[str, Any]] | None = None,
    add_generation_prompt: bool = True,
) -> str:
    """Render conversation messages into ChatML prompt string.

    Ensures prefix stability across turns: when a new turn is appended,
    the rendered prefix of previous turns remains identical byte-for-byte.
    """
    rendered_parts: list[str] = []

    # Format tools deterministically if provided
    tools_header = ""
    if tools:
        tool_dicts = [t.model_dump() if isinstance(t, ToolDefinition) else t for t in tools]
        # Sort keys deterministically using stable_json
        tools_str = stable_json(tool_dicts)
        tools_header = (
            f"\n\n# Tools\nYou have access to the following tools:\n{tools_str}\n"
            "To call a tool, reply with: <tool_call>\n"
            '{"name": "tool_name", "arguments": {"arg": "value"}}\n</tool_call>'
        )

    for i, raw_msg in enumerate(messages):
        msg = raw_msg if isinstance(raw_msg, ChatMessage) else ChatMessage.model_validate(raw_msg)
        content = msg.content
        if i == 0 and msg.role == "system" and tools_header:
            content += tools_header

        # Format tool calls in assistant turn if present
        if msg.tool_calls:
            call_strs = [
                f"<tool_call>\n{stable_json(call)}\n</tool_call>" for call in msg.tool_calls
            ]
            content = f"{content}\n" + "\n".join(call_strs) if content else "\n".join(call_strs)

        rendered_parts.append(f"{IM_START}{msg.role}\n{content}{IM_END}\n")

    rendered = "".join(rendered_parts)

    if add_generation_prompt:
        rendered += f"{IM_START}assistant\n"

    return rendered


def tokenize_chatml(text: str) -> list[str]:
    """Tokenize ChatML text preserving special delimiter tokens.

    Splits on whitespace and punctuation while keeping <|im_start|> and <|im_end|> intact.
    """
    token_pattern = re.compile(r"(<\|im_start\|>|<\|im_end\|>|[a-zA-Z0-9_]+|[^\s\w]|\s+)")
    tokens = [m.group(0) for m in token_pattern.finditer(text) if m.group(0)]
    return tokens


def check_prefix_stability(prefix_tokens: list[str], full_tokens: list[str]) -> bool:
    """Check whether full_tokens starts with prefix_tokens verbatim."""
    if len(full_tokens) < len(prefix_tokens):
        return False
    return full_tokens[: len(prefix_tokens)] == prefix_tokens


def parse_tool_calls(text: str) -> list[dict[str, Any]]:
    """Parse structured <tool_call> JSON blocks from assistant output."""
    pattern = re.compile(r"<tool_call>\s*(\{.*?\})\s*</tool_call>", re.DOTALL)
    calls: list[dict[str, Any]] = []

    for match in pattern.finditer(text):
        raw_json = match.group(1)
        try:
            parsed = json.loads(raw_json)
            if isinstance(parsed, dict) and "name" in parsed:
                calls.append(parsed)
        except json.JSONDecodeError:
            continue

    return calls
